// Results tab and PGN import in headless Chromium. Usage: VIEWPORT=desktop|phone CHESSCOM=<user> node scripts/stats-pgn-check.mjs [baseUrl]
import { mkdirSync } from 'node:fs';
import { chromium, devices } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:4173/';
const vp = process.env.VIEWPORT ?? 'desktop';
const out = new URL(`../shots/${vp}/`, import.meta.url);
mkdirSync(out, { recursive: true });
const shot = (p, n) => p.screenshot({ path: new URL(`${n}.png`, out).pathname, fullPage: true });
const browser = await chromium.launch();
const page = await (await browser.newContext({ ...(vp === 'phone' ? devices['Pixel 7'] : { viewport: { width: 1440, height: 900 } }), colorScheme: 'dark' })).newPage();
const problems = [];
page.on('console', (m) => m.type() === 'error' && !/ERR_SSL_PROTOCOL_ERROR/.test(m.text()) && problems.push(m.text()));
page.on('pageerror', (e) => problems.push(String(e)));
await page.goto(base);
await page.fill('input >> nth=1', process.env.CHESSCOM ?? 'hikaru');
await page.click('button.primary');
await page.waitForSelector('.card-preview img', { timeout: 120_000 });
await page.click('.tabbar button >> nth=3');
await page.click('button:has-text("Results")');
await page.waitForTimeout(800);
await shot(page, 's1-results');
console.log('rating chart:', !!(await page.$('.chart svg path.series')));
await page.click('.tabbar button >> nth=2');
await page.click('button:has-text("Import PGN")');
const pgn = `[Event "vs bot"]\n[Date "2026.11.18"]\n[White "Tester"]\n[Black "Bot"]\n[Result "1-0"]\n[TimeControl "600"]\n\n1. e4 e5 2. Nf3 Nc6 3. Bc4 Bc5 4. c3 Nf6 5. d4 exd4 6. cxd4 Bb4+ 7. Nc3 Nxe4 8. O-O Bxc3 9. d5 Bf6 10. Re1 Ne7 11. Rxe4 d6 12. Bg5 Bxg5 13. Nxg5 h6 14. Qe2 hxg5 15. Re1 Be6 16. dxe6 f6 17. Re3 c6 18. Rh3 Rxh3 19. gxh3 g6 20. Qf3 Qa5 21. Rd1 1-0\n\n[Event "vs bot"]\n[Date "2026.11.18"]\n[White "Bot"]\n[Black "Tester"]\n[Result "0-1"]\n\n1. d4 d5 2. c4 e6 3. Nc3 Nf6 4. Bg5 Be7 0-1\n`;
await page.fill('.pgn-import textarea', pgn);
await page.waitForTimeout(200);
console.log((await page.$eval('.pgn-import .hint >> nth=1', (e) => e.textContent)).trim());
await shot(page, 's2-pgn');
await page.click('.pgn-import button.primary');
await page.waitForSelector('.pgn-import .hint:has-text("Imported")', { timeout: 30_000 });
await page.waitForTimeout(800);
const rows = await page.$$eval('.game-row', (els) => els.filter((e) => e.textContent.includes('vs Bot')).length);
console.log('imported games listed:', rows);
const card = await page.evaluate(() => window.__report?.card?.subtitle);
console.log('card subtitle now:', card);
console.log(problems.length ? `PROBLEMS:\n${problems.join('\n')}` : 'no console errors');
await browser.close();
